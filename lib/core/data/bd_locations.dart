  /// Returns sorted list of all 8 divisions
  static List<String> getDivisions() {
    final list = data.keys.toList();
    list.sort();
    return list;
  }

  /// Returns sorted list of districts for a given division
  static List<String> getDistricts(String division) {
    if (division.isEmpty || !data.containsKey(division)) {
      return [];
    }
    final list = data[division]!.keys.toList();
    list.sort();
    return list;
  }

  /// Returns sorted list of upazilas for a given district
  static List<String> getUpazilas(String district) {
    if (district.isEmpty) return [];
    for (final divisionMap in data.values) {
      if (divisionMap.containsKey(district)) {
        final list = List<String>.from(divisionMap[district]!);
        list.sort();
        return list;
      }
    }
    return [];
  }

  /// Returns upazilas given both division and district
  static List<String> getUpazilasByDivisionAndDistrict(
      String division, String district) {
    if (division.isEmpty || district.isEmpty) return [];
    final divMap = data[division];
    if (divMap != null && divMap.containsKey(district)) {
      final list = List<String>.from(divMap[district]!);
      list.sort();
      return list;
    }
    return getUpazilas(district);
  }
